<?php

declare(strict_types=1);

use App\Database;
use App\Repository\AdminRepository;
use App\Repository\ModerationRepository;

require_once dirname(__DIR__) . '/vendor/autoload.php';

$passed = 0;
$failed = 0;
$connection = null;
$assert = static function (bool $condition, string $message = 'Warunek testu nie został spełniony.'): void {
    if (!$condition) {
        throw new RuntimeException($message);
    }
};
$throws = static function (callable $operation, string $class) use ($assert): void {
    try {
        $operation();
    } catch (Throwable $exception) {
        $assert($exception instanceof $class, 'Nieoczekiwany wyjątek: ' . $exception::class);
        return;
    }
    $assert(false, 'Oczekiwano wyjątku: ' . $class);
};

try {
    $connection = (new Database())->connect();
    $connection->beginTransaction();
    $connection->exec('CREATE TEMP TABLE users (
        id BIGINT PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(255) NOT NULL,
        is_moderator BOOLEAN NOT NULL DEFAULT false
    ) ON COMMIT DROP');
    $connection->exec('CREATE TEMP TABLE user_bans (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        user_id BIGINT NOT NULL REFERENCES pg_temp.users (id), moderator_id BIGINT NULL, reason TEXT NOT NULL DEFAULT \'\', starts_at TIMESTAMPTZ NOT NULL,
        ends_at TIMESTAMPTZ NOT NULL, revoked_at TIMESTAMPTZ NULL
    ) ON COMMIT DROP');
    $connection->exec('CREATE TEMP TABLE community_reports (target_type TEXT NOT NULL, status TEXT NOT NULL) ON COMMIT DROP');
    $connection->exec('CREATE TEMP TABLE anime (LIKE public.anime INCLUDING ALL) ON COMMIT DROP');
    $migration = file_get_contents(dirname(__DIR__) . '/database/29-admin-diagnostics.sql');
    $assert(is_string($migration));
    $migration = str_replace(['BEGIN;', 'COMMIT;', 'CREATE TABLE IF NOT EXISTS'], ['', '', 'CREATE TEMP TABLE IF NOT EXISTS'], $migration);
    $connection->exec($migration);
    $connection->exec($migration);
    foreach (['users', 'user_bans', 'community_reports', 'anime', 'admin_actions'] as $table) {
        $verify = $connection->prepare("SELECT relnamespace = pg_my_temp_schema() AND relpersistence = 't'
            FROM pg_class WHERE oid = to_regclass(:table)");
        $verify->execute(['table' => $table]);
        $assert($verify->fetchColumn() === true, 'Testy zapisują wyłącznie własne tabele tymczasowe.');
    }
    $connection->exec("INSERT INTO pg_temp.users (id, name, email, is_moderator, is_admin) VALUES
        (1,'Administrator','admin@example.test',false,true),
        (2,'Drugi administrator','admin2@example.test',false,true),
        (3,'Użytkownik','user@example.test',false,false),
        (4,'Moderator','moderator@example.test',true,false),
        (5,'Zablokowany administrator','banned-admin@example.test',false,true),
        (6,'Zablokowane konto','banned@example.test',false,false),
        (7,'Wygasła blokada','expired@example.test',false,true),
        (8,'Literalne %_ znaki','literal@example.test',false,false)");
    $connection->exec("INSERT INTO pg_temp.users (id,name,email)
        SELECT n, 'Konto ' || n, 'account-' || n || '@example.test' FROM generate_series(9,35) n");
    $connection->exec("INSERT INTO pg_temp.user_bans (user_id,starts_at,ends_at) VALUES
        (5,clock_timestamp()-INTERVAL '1 hour',clock_timestamp()+INTERVAL '1 hour'),
        (6,clock_timestamp()-INTERVAL '1 hour',clock_timestamp()+INTERVAL '1 hour'),
        (7,clock_timestamp()-INTERVAL '2 hours',clock_timestamp()-INTERVAL '1 hour')");
    $connection->exec("INSERT INTO pg_temp.community_reports VALUES ('comment','open'),('comment','removed'),('message','open')");
    $connection->exec("INSERT INTO pg_temp.anime (id,title,description,cover_url) VALUES
        (1,'Anime %_ A','','https://example.test/a.jpg'),
        (2,'Anime B','Opis',NULL), (3,'Anime C','Opis','  '),
        (4,'Anime D','  ','https://example.test/d.jpg')");
    $repository = new AdminRepository($connection);
    $run = static function (string $name, callable $operation) use ($connection, &$passed, &$failed): void {
        $connection->exec('SAVEPOINT admin_repository_test');
        try {
            $operation();
            $passed++;
            echo '[OK] ' . $name . PHP_EOL;
        } catch (Throwable $exception) {
            $failed++;
            fwrite(STDERR, '[BŁĄD] ' . $name . ': ' . $exception->getMessage() . PHP_EOL);
        } finally {
            $connection->exec('ROLLBACK TO SAVEPOINT admin_repository_test');
            $connection->exec('RELEASE SAVEPOINT admin_repository_test');
        }
    };

    $run('Rola administratora jest niezależna od moderatora i uwzględnia aktywny ban', static function () use ($repository, $connection, $assert): void {
        $assert($repository->isAdmin(1));
        $assert(!$repository->isAdmin(3) && !$repository->isAdmin(4));
        $assert(!$repository->isAdmin(5) && !$repository->isAdmin(999999) && !$repository->isAdmin(0));
        $assert($repository->isAdmin(7));
        $connection->exec('UPDATE pg_temp.user_bans SET revoked_at = clock_timestamp() WHERE user_id = 5');
        $assert($repository->isAdmin(5));
        $connection->exec('UPDATE pg_temp.users SET is_admin = false WHERE id = 1');
        $assert(!$repository->isAdmin(1), 'Odebranie roli obowiązuje przy następnym sprawdzeniu.');
    });

    $run('Przegląd liczy wyłącznie zgłoszenia publicznych komentarzy', static function () use ($repository, $assert): void {
        $assert($repository->overview() === ['users' => 35, 'anime' => 4, 'openCommentReports' => 1]);
    });

    $run('Moderator nie może zbanować administratora bez roli moderatora', static function () use ($connection, $assert): void {
        $moderation = new ModerationRepository($connection);
        $assert(!$moderation->banUser(4, 1, 'Próba blokady administratora', 3600, str_repeat('a', 32)));
        $assert($moderation->activeBanForUser(1) === null);
    });

    $run('Wyszukiwanie kont traktuje znaki SQL dosłownie i ogranicza strony', static function () use ($repository, $assert): void {
        $users = $repository->users('', 999);
        $assert($users['pagination'] === ['page' => 2, 'perPage' => 20, 'total' => 35, 'totalPages' => 2]);
        $assert(count($users['items']) === 15);
        $literal = $repository->users('%_');
        $assert(count($literal['items']) === 1 && $literal['items'][0]['id'] === 8);
        $assert($repository->users("' OR 1=1 --")['items'] === []);
        $assert($repository->users('ADMIN@EXAMPLE.TEST')['items'][0]['isAdmin'] === true);
        $assert($repository->users('banned-admin')['items'][0]['banEndsAt'] !== null);
        $assert($repository->users('expired@example.test')['items'][0]['banEndsAt'] === null);
    });

    $run('Zmiana moderatora wymaga aktualnego admina i chroni własne, administracyjne i zablokowane konto', static function () use ($repository, $assert): void {
        foreach ([[3,4], [4,3], [5,3], [1,1], [1,2], [1,5], [1,6], [1,999999]] as [$actor, $target]) {
            $assert(!$repository->changeModerator($actor, $target, true, 'Kontrola uprawnień'));
        }
        $assert($repository->history()['pagination']['total'] === 0);
    });

    $run('Nadanie i odebranie moderatora zapisują powód w audycie bez duplikowania powtórzenia', static function () use ($repository, $assert): void {
        $assert($repository->changeModerator(1, 3, true, '  Pomoc w moderacji  '));
        $assert($repository->users('user@example.test')['items'][0]['isModerator']);
        $assert(!$repository->changeModerator(1, 3, true, 'Ponowienie formularza'));
        $history = $repository->history();
        $assert($history['pagination']['total'] === 1);
        $assert($history['items'][0]['action'] === 'moderator_granted');
        $assert($history['items'][0]['actorId'] === 1 && $history['items'][0]['targetId'] === 3);
        $assert($history['items'][0]['details'] === ['reason' => 'Pomoc w moderacji']);
        $assert($repository->changeModerator(1, 3, false, 'Koniec dyżuru'));
        $assert(!$repository->users('user@example.test')['items'][0]['isModerator']);
        $assert($repository->history()['items'][0]['action'] === 'moderator_revoked');
    });

    $run('Nieprawidłowe powody i szczegóły audytu są odrzucane przed zapisem', static function () use ($repository, $throws, $assert): void {
        foreach (['', '  ', str_repeat('ą', 1001), "Powód\nnowa linia", "NUL\0"] as $reason) {
            $throws(static fn () => $repository->changeModerator(1, 3, true, $reason), InvalidArgumentException::class);
        }
        foreach ([['password' => 'secret'], ['reason' => ['nested']], ['reason' => str_repeat('x', 4001)]] as $details) {
            $throws(static fn () => $repository->audit(1, 'diagnostics_checked', null, $details), InvalidArgumentException::class);
        }
        $throws(static fn () => $repository->audit(1, 'invalid action'), InvalidArgumentException::class);
        $throws(static fn () => $repository->audit(3, 'diagnostics_checked'), RuntimeException::class);
        $assert($repository->history()['pagination']['total'] === 0);
    });

    $run('Błąd audytu wycofuje zmianę roli i zachowuje nadrzędną transakcję', static function () use ($repository, $connection, $throws, $assert): void {
        $connection->exec("ALTER TABLE pg_temp.admin_actions ADD CONSTRAINT reject_test_action CHECK (action <> 'moderator_granted')");
        $throws(static fn () => $repository->changeModerator(1, 3, true, 'Pomoc w moderacji'), PDOException::class);
        $assert($connection->inTransaction());
        $assert(!$repository->users('user@example.test')['items'][0]['isModerator']);
        $assert($repository->history()['pagination']['total'] === 0);
    });

    $run('CLI chroni ostatniego aktywnego admina i nie nadaje roli zbanowanemu kontu', static function () use ($repository, $throws, $assert): void {
        $assert(!$repository->setAdmin(6, true) && !$repository->setAdmin(999999, true));
        $assert($repository->setAdmin(2, false));
        $assert($repository->setAdmin(7, false));
        $throws(static fn () => $repository->setAdmin(1, false), RuntimeException::class);
        $assert($repository->isAdmin(1));
        $assert($repository->setAdmin(3, true));
        $assert($repository->setAdmin(1, false));
        $assert(!$repository->isAdmin(1) && $repository->isAdmin(3));
        $history = $repository->history();
        $assert($history['pagination']['total'] === 4);
        $assert($history['items'][0]['actorName'] === 'CLI' && $history['items'][0]['actorId'] === null);
        $assert($repository->setAdmin(3, true));
        $assert($repository->history()['pagination']['total'] === 4);
    });

    $run('Katalog pokazuje rzeczywiste braki opisów i okładek oraz filtruje dosłownie', static function () use ($repository, $assert, $throws): void {
        $catalog = $repository->catalog();
        $assert($catalog['summary']['total'] === 4 && $catalog['summary']['missingDescription'] === 2
            && $catalog['summary']['missingImage'] === 2 && $catalog['summary']['lastUpdatedAt'] !== null);
        $assert($repository->catalog('', 'description')['pagination']['total'] === 2);
        $assert($repository->catalog('', 'image')['pagination']['total'] === 2);
        $literal = $repository->catalog('%_');
        $assert(count($literal['items']) === 1 && $literal['items'][0]['id'] === 1);
        $assert($literal['items'][0]['hasImage'] && !$literal['items'][0]['hasDescription']);
        $assert($repository->catalog("' OR 1=1 --")['items'] === []);
        $throws(static fn () => $repository->catalog('', 'DROP TABLE'), InvalidArgumentException::class);
        $throws(static fn () => $repository->users(str_repeat('x', 256)), InvalidArgumentException::class);
    });

    $run('Historia zachowuje migawki nazw oraz ogranicza i porządkuje strony', static function () use ($repository, $connection, $assert): void {
        for ($index = 0; $index < 25; $index++) {
            $repository->audit(1, 'diagnostics_checked', null, ['service' => 'database', 'result' => 'ok']);
        }
        $connection->exec("UPDATE pg_temp.users SET name = 'Zmieniona nazwa' WHERE id = 1");
        $history = $repository->history();
        $assert(count($history['items']) === 20 && $history['pagination']['total'] === 25);
        $assert($history['items'][0]['actorName'] === 'Administrator');
        $assert($history['items'][0]['id'] > $history['items'][19]['id']);
        $assert(count($repository->history(999)['items']) === 5);
    });
} catch (Throwable $exception) {
    $failed++;
    fwrite(STDERR, '[BŁĄD] Przygotowanie testów administracji: ' . $exception->getMessage() . PHP_EOL);
} finally {
    if ($connection instanceof PDO && $connection->inTransaction()) {
        $connection->rollBack();
    }
}

echo sprintf('Wynik: %d poprawnych, %d błędnych.', $passed, $failed) . PHP_EOL;
exit($failed === 0 ? 0 : 1);
