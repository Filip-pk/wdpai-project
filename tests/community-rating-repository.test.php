<?php

declare(strict_types=1);

use App\Database;
use App\Repository\RatingRepository;

require_once dirname(__DIR__) . '/vendor/autoload.php';

$connection = null;
$passed = 0;
$failed = 0;
$assert = static function (bool $condition, string $message): void {
    if (!$condition) {
        throw new RuntimeException($message);
    }
};

try {
    $connection = (new Database())->connect();
    $connection->beginTransaction();
    $connection->exec(<<<'SQL'
CREATE TEMP TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL,
    email TEXT NOT NULL
) ON COMMIT DROP;
CREATE TEMP TABLE anime (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title TEXT NOT NULL,
    score NUMERIC(4, 2) NULL
) ON COMMIT DROP;
CREATE TEMP TABLE user_anime_ratings (
    user_id BIGINT NOT NULL REFERENCES pg_temp.users (id) ON DELETE CASCADE,
    anime_id BIGINT NOT NULL REFERENCES pg_temp.anime (id) ON DELETE CASCADE,
    rating SMALLINT NOT NULL CHECK (rating BETWEEN 1 AND 10),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, anime_id)
) ON COMMIT DROP;
SQL);
    foreach (['users', 'anime', 'user_anime_ratings'] as $table) {
        $check = $connection->prepare("SELECT relnamespace = pg_my_temp_schema() AND relpersistence = 't' FROM pg_class WHERE oid = to_regclass(:table)");
        $check->execute(['table' => $table]);
        $assert(in_array($check->fetchColumn(), [true, 1, '1', 't'], true), 'Test writes require session-local tables.');
    }
    foreach (['users', 'anime'] as $table) {
        $check = $connection->prepare("SELECT relnamespace = pg_my_temp_schema() AND relpersistence = 't' FROM pg_class WHERE oid = pg_get_serial_sequence(:table, 'id')::regclass");
        $check->execute(['table' => $table]);
        $assert(in_array($check->fetchColumn(), [true, 1, '1', 't'], true), 'Test identities require independent temporary sequences.');
    }
    $connection->exec(<<<'SQL'
INSERT INTO pg_temp.users (id, name, email) VALUES
    (101, 'First private name', 'first@example.test'),
    (202, 'Second private name', 'second@example.test'),
    (303, 'Third private name', 'third@example.test');
INSERT INTO pg_temp.anime (id, title, score) VALUES
    (401, 'Imported score exists', 9.87),
    (402, 'Other anime', 7.10),
    (403, 'No imported score', NULL);
SQL);
    $ratings = new RatingRepository($connection);
    $run = static function (string $name, Closure $test) use ($connection, &$passed, &$failed): void {
        $connection->exec('SAVEPOINT community_rating_test');
        try {
            $test();
            $passed++;
            echo 'PASS ' . $name . PHP_EOL;
        } catch (Throwable $exception) {
            $failed++;
            fwrite(STDERR, 'FAIL ' . $name . ': ' . $exception->getMessage() . PHP_EOL);
        } finally {
            $connection->exec('ROLLBACK TO SAVEPOINT community_rating_test');
            $connection->exec('RELEASE SAVEPOINT community_rating_test');
        }
    };

    $run('empty and unrated selections return null averages without importing the catalog score', static function () use ($ratings, $assert): void {
        $assert($ratings->communityForAnimeIds([]) === [], 'Empty selection is empty.');
        $assert($ratings->communityForAnimeIds([401, 403, 999]) === [
            401 => ['average' => null, 'count' => 0],
            403 => ['average' => null, 'count' => 0],
            999 => ['average' => null, 'count' => 0],
        ], 'Unrated, source-rated and missing anime have no community votes.');
    });

    $run('one vote contributes once and duplicate requested IDs never duplicate its count', static function () use ($ratings, $assert): void {
        $ratings->saveForUser(101, 401, 8);
        $assert($ratings->communityForAnimeIds([401, 401]) === [401 => ['average' => 8.0, 'count' => 1]], 'Unique voter-anime pair counted once.');
        $assert($ratings->communityForAnimeIds([402])[402] === ['average' => null, 'count' => 0], 'Another anime remains unrated.');
    });

    $run('batched averages combine accounts per anime without rounding', static function () use ($ratings, $assert): void {
        $ratings->saveForUser(101, 401, 1);
        $ratings->saveForUser(202, 401, 3);
        $ratings->saveForUser(303, 401, 4);
        $ratings->saveForUser(101, 402, 10);
        $result = $ratings->communityForAnimeIds([402, 401, 403]);
        $assert($result[401]['count'] === 3 && abs($result[401]['average'] - 8 / 3) < 0.000000001, 'Full average precision retained.');
        $assert($result[402] === ['average' => 10.0, 'count' => 1], 'Second anime independently aggregated.');
        $assert($result[403] === ['average' => null, 'count' => 0], 'Third anime remains unrated.');
    });

    $run('changing an existing rating replaces its contribution without increasing the voter count', static function () use ($ratings, $assert): void {
        $ratings->saveForUser(101, 401, 2);
        $ratings->saveForUser(202, 401, 6);
        $assert($ratings->communityForAnimeIds([401])[401] === ['average' => 4.0, 'count' => 2], 'Initial contribution.');
        $ratings->saveForUser(101, 401, 10);
        $assert($ratings->communityForAnimeIds([401])[401] === ['average' => 8.0, 'count' => 2], 'Upsert changes aggregate immediately.');
    });

    $run('removing a rating immediately removes its contribution and the last removal restores null', static function () use ($ratings, $assert): void {
        $ratings->saveForUser(101, 401, 2);
        $ratings->saveForUser(202, 401, 8);
        $ratings->removeForUser(101, 401);
        $assert($ratings->communityForAnimeIds([401])[401] === ['average' => 8.0, 'count' => 1], 'Removal reflected immediately.');
        $ratings->removeForUser(202, 401);
        $assert($ratings->communityForAnimeIds([401])[401] === ['average' => null, 'count' => 0], 'No stale average after final removal.');
    });

    $run('existing and externally imported rating writes contribute without synchronizing a second table', static function () use ($ratings, $connection, $assert): void {
        $connection->exec('INSERT INTO user_anime_ratings (user_id, anime_id, rating) VALUES (101, 401, 9), (202, 401, 5)');
        $assert($ratings->communityForAnimeIds([401])[401] === ['average' => 7.0, 'count' => 2], 'Existing or imported rows included.');
        $connection->exec('UPDATE user_anime_ratings SET rating = 7 WHERE user_id = 202 AND anime_id = 401');
        $assert($ratings->communityForAnimeIds([401])[401] === ['average' => 8.0, 'count' => 2], 'External update visible immediately.');
        $assert((float) $connection->query('SELECT score FROM anime WHERE id = 401')->fetchColumn() === 9.87, 'Source score remains unchanged.');
    });

    $run('public summaries expose only averages and counts while personal rating reads remain account scoped', static function () use ($ratings, $assert): void {
        $ratings->saveForUser(101, 401, 9);
        $ratings->saveForUser(202, 401, 5);
        $summary = $ratings->communityForAnimeIds([401])[401];
        $assert(array_keys($summary) === ['average', 'count'], 'No voter IDs, names, individual values or account data in public summary.');
        $assert($ratings->findForUser(101, 401) === 9 && $ratings->findForUser(202, 401) === 5, 'Personal reads preserved.');
        $assert($ratings->findForUser(303, 401) === null, 'No other account rating inherited.');
        $assert($ratings->findByAnimeIdsForUser(101, [401, 402]) === [401 => 9], 'Batch personal API unchanged.');
    });

    $run('account and anime deletion remove only the corresponding contributions', static function () use ($ratings, $connection, $assert): void {
        $ratings->saveForUser(101, 401, 9);
        $ratings->saveForUser(202, 401, 5);
        $ratings->saveForUser(202, 402, 7);
        $connection->exec('DELETE FROM pg_temp.users WHERE id = 101');
        $assert($ratings->communityForAnimeIds([401])[401] === ['average' => 5.0, 'count' => 1], 'Deleted account contribution removed.');
        $connection->exec('DELETE FROM pg_temp.anime WHERE id = 401');
        $assert($ratings->communityForAnimeIds([401, 402]) === [
            401 => ['average' => null, 'count' => 0],
            402 => ['average' => 7.0, 'count' => 1],
        ], 'Unrelated anime votes preserved.');
    });

    $run('invalid batch identifiers are rejected consistently with personal batch reads', static function () use ($ratings, $assert): void {
        foreach ([[0], [-1], ['401'], [401.0], [true], [null], [[401]], [401, 'bad']] as $ids) {
            $rejected = false;
            try {
                $ratings->communityForAnimeIds($ids);
            } catch (InvalidArgumentException) {
                $rejected = true;
            }
            $assert($rejected, 'Only positive integer identifiers accepted.');
        }
    });

    $run('large sparse selections preserve every requested anime without extending the result set', static function () use ($ratings, $assert): void {
        $ratings->saveForUser(101, 401, 8);
        $ratings->saveForUser(202, 402, 3);
        $ids = [401, ...range(1000, 1199)];
        $result = $ratings->communityForAnimeIds($ids);
        $assert(count($result) === count($ids) && array_keys($result) === $ids, 'Every selected ID appears once in selection order.');
        $assert($result[401] === ['average' => 8.0, 'count' => 1] && $result[1199] === ['average' => null, 'count' => 0], 'Rated and absent entries projected correctly.');
        $assert(!array_key_exists(402, $result), 'Unrequested anime are excluded.');
    });
} catch (Throwable $exception) {
    $failed++;
    fwrite(STDERR, 'FAIL fixture setup: ' . $exception->getMessage() . PHP_EOL);
} finally {
    if ($connection instanceof PDO && $connection->inTransaction()) {
        $connection->rollBack();
    }
}

echo $passed . ' passed, ' . $failed . ' failed.' . PHP_EOL;
exit($failed === 0 ? 0 : 1);
