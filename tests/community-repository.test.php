    fwrite(STDERR, 'FAIL fixture setup: ' . $exception->getMessage() . PHP_EOL);
} finally {
    if ($connection->inTransaction()) {
        $connection->rollBack();
    }
}

fwrite(STDOUT, $passed . ' passed, ' . $failed . ' failed.' . PHP_EOL);
exit($failed === 0 ? 0 : 1);
