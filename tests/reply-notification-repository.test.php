<?php

declare(strict_types=1);

use App\Database;
use App\Repository\ReplyNotificationRepository;

require_once dirname(__DIR__) . '/vendor/autoload.php';

$connection = (new Database())->connect();
$connection->beginTransaction();
$passed = 0;
$failed = 0;
$assert = static function (bool $condition, string $message): void {
    if (!$condition) {
        throw new RuntimeException($message);
    }
};

try {
    $connection->exec(<<<'SQL'
CREATE TEMP TABLE users (id BIGINT PRIMARY KEY, name TEXT NOT NULL) ON COMMIT DROP;
CREATE TEMP TABLE anime (id BIGINT PRIMARY KEY, title TEXT NOT NULL) ON COMMIT DROP;
CREATE TEMP TABLE anime_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    anime_id BIGINT NOT NULL REFERENCES pg_temp.anime(id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES pg_temp.users(id) ON DELETE CASCADE,
    parent_id BIGINT NULL REFERENCES pg_temp.anime_comments(id) ON DELETE CASCADE,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    moderated_at TIMESTAMPTZ NULL,
    deleted_at TIMESTAMPTZ NULL
) ON COMMIT DROP;
CREATE TEMP TABLE comment_reply_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 2000) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES pg_temp.users(id) ON DELETE CASCADE,
    reply_id BIGINT NOT NULL REFERENCES pg_temp.anime_comments(id) ON DELETE CASCADE UNIQUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    read_at TIMESTAMPTZ NULL
) ON COMMIT DROP;
INSERT INTO users (id, name) VALUES (101, 'Author <svg>'), (102, 'Reply author'), (103, 'Outsider');
INSERT INTO anime (id, title) VALUES (201, 'Test anime <script>'), (202, 'Other anime');
INSERT INTO anime_comments (id, anime_id, user_id, parent_id, body) VALUES
    (301, 201, 101, NULL, 'Root comment'),
    (302, 201, 102, 301, 'First received reply'),
    (303, 201, 101, 301, 'Own reply'),
    (304, 201, 103, 301, 'Second received reply'),
    (305, 202, 102, NULL, 'Another author root'),
    (306, 202, 101, 305, 'Reply to second author');
SQL);
    foreach (['users', 'anime', 'anime_comments', 'comment_reply_notifications'] as $table) {
        $statement = $connection->prepare('SELECT to_regclass(:table) = to_regclass(:temp)');
        $statement->execute(['table' => $table, 'temp' => 'pg_temp.' . $table]);
        $assert($statement->fetchColumn() === true, 'Fixture must use TEMP table: ' . $table);
    }
    foreach (['anime_comments', 'comment_reply_notifications'] as $table) {
        $statement = $connection->prepare("SELECT relnamespace = pg_my_temp_schema() AND relpersistence = 't' FROM pg_class WHERE oid = pg_get_serial_sequence(:table, 'id')::regclass");
        $statement->execute(['table' => 'pg_temp.' . $table]);
        $assert($statement->fetchColumn() === true, 'Fixture must use independent TEMP identity: ' . $table);
    }

    $repository = new ReplyNotificationRepository($connection);
    $tests = [];
    $tests['notifications belong only to the parent author and never duplicate or notify oneself'] = static function () use ($repository, $assert): void {
        $assert($repository->createForReply(302), 'A different author reply creates notification');
        $assert(!$repository->createForReply(302), 'Duplicate reply does not create another notification');
        $assert(!$repository->createForReply(303), 'Self reply creates no notification');
        $assert(!$repository->createForReply(301), 'Root comment cannot create notification');
        $assert(!$repository->createForReply(999999), 'Missing reply creates no notification');
        $assert($repository->unreadCountForUser(101) === 1, 'Only root author has one unread notification');
        $assert($repository->unreadCountForUser(102) === 0, 'Reply author has none');
        $assert($repository->findPageForUser(103)['total'] === 0, 'Unrelated user has none');
    };
    $tests['reads and lookups cannot access another account notification'] = static function () use ($repository, $assert): void {
        $repository->createForReply(302);
        $entry = $repository->findPageForUser(101)['entries'][0];
        $assert($repository->findByIdForUser(103, $entry['id']) === null, 'Outsider cannot look up notification');
        $assert(!$repository->markReadForUser(103, $entry['id']), 'Outsider cannot acknowledge notification');
        $assert(!$repository->markAllReadForUser(103, $entry['id']), 'Foreign snapshot cannot clear notifications');
        $assert($repository->unreadCountForUser(101) === 1, 'Rejected writes preserve author count');
        $assert($repository->markReadForUser(101, $entry['id']), 'Owner acknowledges notification');
        $assert($repository->markReadForUser(101, $entry['id']), 'Acknowledgement is idempotent');
        $assert($repository->unreadCountForUser(101) === 0, 'Owner count becomes zero');
    };
    $tests['mark all acknowledges only the owned snapshot and leaves newer replies unread'] = static function () use ($repository, $assert): void {
        $repository->createForReply(302);
        $snapshot = $repository->findPageForUser(101)['snapshotId'];
        $repository->createForReply(304);
        $repository->createForReply(306);
        $assert($repository->markAllReadForUser(101, $snapshot), 'Known owned snapshot accepted');
        $assert($repository->unreadCountForUser(101) === 1, 'Newer incoming reply remains unread');
        $assert($repository->unreadCountForUser(102) === 1, 'Other author remains unread');
        $assert(!$repository->markAllReadForUser(101, 0), 'Zero cursor rejected');
        $assert(!$repository->markAllReadForUser(101, 999999), 'Unknown cursor rejected');
    };
    $tests['notifications expose metadata without comment body or private account columns'] = static function () use ($repository, $assert): void {
        $repository->createForReply(302);
        $entry = $repository->findPageForUser(101)['entries'][0];
        $assert(array_keys($entry) === ['id', 'replyId', 'parentId', 'animeId', 'animeTitle', 'authorName', 'createdAt', 'isRead', 'replyPage'], 'Only required public metadata projected');
        $assert($entry['parentId'] === 301 && $entry['replyId'] === 302 && $entry['animeId'] === 201, 'Correct target identifiers');
        $assert($entry['animeTitle'] === 'Test anime <script>' && $entry['authorName'] === 'Reply author', 'Presentation will escape the original metadata');
        $assert($entry['replyPage'] === 1 && !$entry['isRead'], 'Initial page and unread status are correct');
    };
    $tests['hidden or deleted replies disappear from notifications while root tombstones preserve access'] = static function () use ($repository, $connection, $assert): void {
        $repository->createForReply(302);
        $connection->exec('UPDATE anime_comments SET deleted_at = clock_timestamp() WHERE id = 301');
        $assert($repository->unreadCountForUser(101) === 1, 'Preserved thread remains reachable after root deletion');
        $assert($repository->findPageForUser(101)['total'] === 1, 'Reply metadata remains available');
        $connection->exec('UPDATE anime_comments SET moderated_at = clock_timestamp() WHERE id = 302');
        $assert($repository->unreadCountForUser(101) === 0, 'Hidden reply is not an unread notification');
        $assert($repository->findPageForUser(101)['total'] === 0, 'Hidden reply does not appear in metadata list');
        $assert(!$repository->createForReply(304), 'New notification is not created for a deleted root');
    };
    $tests['pagination is stable and open links locate late replies on the correct thread page'] = static function () use ($repository, $connection, $assert): void {
        $insert = $connection->prepare('INSERT INTO anime_comments (anime_id, user_id, parent_id, body) VALUES (201, 102, 301, :body) RETURNING id');
        for ($index = 0; $index < 22; $index++) {
            $insert->execute(['body' => 'Reply ' . $index]);
            $repository->createForReply((int) $insert->fetchColumn());
        }
        $first = $repository->findPageForUser(101);
        $second = $repository->findPageForUser(101, 2);
        $assert($first['total'] === 22 && $first['totalPages'] === 2 && count($first['entries']) === 20, 'Page one has 20 of 22 notifications');
        $assert(count($second['entries']) === 2, 'Last page has remaining notifications');
        $ids = array_column([...$first['entries'], ...$second['entries']], 'id');
        $assert(count(array_unique($ids)) === 22, 'No duplicate rows across pages');
        $assert($first['entries'][0]['replyPage'] === 3, 'Latest reply after existing siblings opens third thread page');
        $assert($repository->findPageForUser(101, 999)['page'] === 2, 'Page clamped to last');
    };
    $tests['hard deletion of a reply cascades only its notification'] = static function () use ($repository, $connection, $assert): void {
        $repository->createForReply(302);
        $repository->createForReply(304);
        $connection->exec('DELETE FROM anime_comments WHERE id = 302');
        $assert($repository->unreadCountForUser(101) === 1, 'Another notification remains');
        $assert($repository->findPageForUser(101)['entries'][0]['replyId'] === 304, 'Remaining reply is unchanged');
    };

    foreach ($tests as $name => $test) {
        $connection->exec('SAVEPOINT reply_notification_test');
        try {
            $test();
            $passed++;
            echo 'PASS ' . $name . PHP_EOL;
        } catch (Throwable $exception) {
            $failed++;
            fwrite(STDERR, 'FAIL ' . $name . ': ' . $exception->getMessage() . PHP_EOL);
        } finally {
            $connection->exec('ROLLBACK TO SAVEPOINT reply_notification_test');
            $connection->exec('RELEASE SAVEPOINT reply_notification_test');
        }
    }
} catch (Throwable $exception) {
    $failed++;
    fwrite(STDERR, 'FAIL fixture setup: ' . $exception->getMessage() . PHP_EOL);
} finally {
    if ($connection->inTransaction()) {
        $connection->rollBack();
    }
}

echo $passed . ' passed, ' . $failed . ' failed.' . PHP_EOL;
exit($failed === 0 ? 0 : 1);
