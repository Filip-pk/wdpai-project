<?php

declare(strict_types=1);

use App\Database;
use App\Repository\CommentReactionRepository;
use App\Repository\CommunityRepository;
use App\Service\CommentReactionService;
use App\Service\RateLimitException;

require_once dirname(__DIR__) . '/vendor/autoload.php';

$connection = null;
$passed = 0;
$failed = 0;
$assert = static function (bool $condition, string $message): void {
    if (!$condition) {
        throw new RuntimeException($message);
    }
};
$exceptionOf = static function (string $class, Closure $operation) use ($assert): Throwable {
    try {
        $operation();
    } catch (Throwable $exception) {
        $assert($exception instanceof $class, 'Unexpected exception: ' . $exception::class . ': ' . $exception->getMessage());
        return $exception;
    }
    throw new RuntimeException('Expected exception: ' . $class);
};

try {
    $connection = (new Database())->connect();
    $connection->beginTransaction();
    $connection->exec(<<<'SQL'
CREATE TEMP TABLE users (id BIGINT PRIMARY KEY) ON COMMIT DROP;
CREATE TEMP TABLE anime (id BIGINT PRIMARY KEY) ON COMMIT DROP;
CREATE TEMP TABLE anime_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES pg_temp.users (id) ON DELETE CASCADE,
    anime_id BIGINT NOT NULL REFERENCES pg_temp.anime (id) ON DELETE CASCADE,
    parent_id BIGINT NULL REFERENCES pg_temp.anime_comments (id) ON DELETE CASCADE,
    body TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    deleted_at TIMESTAMPTZ NULL,
    moderated_at TIMESTAMPTZ NULL
) ON COMMIT DROP;
CREATE TEMP TABLE comment_reactions (
    user_id BIGINT NOT NULL REFERENCES pg_temp.users (id) ON DELETE CASCADE,
    comment_id BIGINT NOT NULL REFERENCES pg_temp.anime_comments (id) ON DELETE CASCADE,
    value SMALLINT NOT NULL CHECK (value IN (-1, 1)),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (user_id, comment_id)
) ON COMMIT DROP;
CREATE TEMP TABLE community_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES pg_temp.users (id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL CHECK (action IN ('message', 'comment', 'report', 'reaction')),
    content_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
) ON COMMIT DROP;
SQL);
    foreach (['users', 'anime', 'anime_comments', 'comment_reactions', 'community_activity'] as $table) {
        $check = $connection->prepare("SELECT relnamespace = pg_my_temp_schema() AND relpersistence = 't' FROM pg_class WHERE oid = to_regclass(:table)");
        $check->execute(['table' => $table]);
        $assert(in_array($check->fetchColumn(), [true, 1, '1', 't'], true), 'All writes require session-local tables.');
    }
    foreach (['anime_comments', 'community_activity'] as $table) {
        $check = $connection->prepare("SELECT relnamespace = pg_my_temp_schema() AND relpersistence = 't' FROM pg_class WHERE oid = pg_get_serial_sequence(:table, 'id')::regclass");
        $check->execute(['table' => $table]);
        $assert(in_array($check->fetchColumn(), [true, 1, '1', 't'], true), 'All generated identities require independent temporary sequences.');
    }
    $connection->exec(<<<'SQL'
INSERT INTO pg_temp.users (id) VALUES (101), (102), (103), (104);
INSERT INTO pg_temp.anime (id) VALUES (201), (202);
INSERT INTO pg_temp.anime_comments (id, user_id, anime_id, parent_id, body) VALUES
    (401, 101, 201, NULL, 'Root by Alice'),
    (402, 102, 201, 401, 'Reply by Bob'),
    (403, 103, 201, NULL, 'Root by Carol'),
    (404, 104, 202, NULL, 'Other anime'),
    (405, 102, 201, NULL, 'Moderated root'),
    (406, 102, 201, NULL, 'Deleted root'),
    (407, 103, 201, 406, 'Visible reply below deleted root');
UPDATE pg_temp.anime_comments SET moderated_at = clock_timestamp() WHERE id = 405;
UPDATE pg_temp.anime_comments SET deleted_at = clock_timestamp() WHERE id = 406;
SQL);
    $reactions = new CommentReactionRepository($connection);
    $community = new CommunityRepository($connection);
    $service = new CommentReactionService($community, $reactions);
    $run = static function (string $name, Closure $test) use ($connection, &$passed, &$failed): void {
        $connection->exec('SAVEPOINT reaction_repository_test');
        try {
            $test();
            $passed++;
            echo 'PASS ' . $name . PHP_EOL;
        } catch (Throwable $exception) {
            $failed++;
            fwrite(STDERR, 'FAIL ' . $name . ': ' . $exception->getMessage() . PHP_EOL);
        } finally {
            $connection->exec('ROLLBACK TO SAVEPOINT reaction_repository_test');
            $connection->exec('RELEASE SAVEPOINT reaction_repository_test');
        }
    };

    $run('batched public counters are empty for missing or hidden targets and never expose voter identity', static function () use ($reactions, $assert): void {
        $assert($reactions->countsForComments([]) === [], 'Empty request needs no rows.');
        $counts = $reactions->countsForComments([401, 401, 405, 406, PHP_INT_MAX, -1, '401) OR TRUE --']);
        $zero = ['likes' => 0, 'dislikes' => 0, 'userReaction' => 0];
        $assert($counts === [401 => $zero, 405 => $zero, 406 => $zero, PHP_INT_MAX => $zero], 'Only positive integer IDs are requested and no private voter columns are projected.');
    });

    $run('valid targets exclude own entries, cross-anime IDs, missing actors and hidden text', static function () use ($reactions, $service, $connection, $assert): void {
        foreach ([[101, 201, 401], [102, 201, 402], [101, 202, 402], [101, 201, PHP_INT_MAX], [999, 201, 402], [101, 201, 405], [101, 201, 406], [0, 201, 402]] as [$actor, $anime, $target]) {
            $assert($reactions->targetForUser($actor, $anime, $target) === null, 'Invalid target must not be available for reactions.');
            foreach ([-1, 0, 1] as $value) {
                $assert(!$service->setForUser($actor, $anime, $target, $value), 'Invalid mutation must fail even if the requested state is zero.');
                $assert(!$reactions->setForUser($actor, $anime, $target, $value), 'Repository write path independently enforces target ownership and visibility.');
            }
        }
        foreach ([-2, 2, PHP_INT_MAX] as $value) {
            $assert(!$service->setForUser(101, 201, 402, $value) && !$reactions->setForUser(101, 201, 402, $value), 'Only -1, 0 and 1 are accepted.');
        }
        $assert((int) $connection->query('SELECT COUNT(*) FROM community_activity')->fetchColumn() === 0, 'Rejected writes never consume quota.');
    });

    $run('explicit desired state is idempotent and one user cannot retain both reaction signs', static function () use ($service, $reactions, $connection, $assert): void {
        $assert($service->setForUser(101, 201, 402, 1), 'Like is accepted.');
        $changedAt = $connection->query('SELECT updated_at FROM comment_reactions WHERE user_id = 101 AND comment_id = 402')->fetchColumn();
        $assert($service->setForUser(101, 201, 402, 1), 'Repeated like is a successful no-op.');
        $assert($connection->query('SELECT updated_at FROM comment_reactions WHERE user_id = 101 AND comment_id = 402')->fetchColumn() === $changedAt, 'No-op does not modify reaction timestamp.');
        $assert((int) $connection->query('SELECT COUNT(*) FROM community_activity')->fetchColumn() === 1, 'No-op does not consume quota.');
        $assert($service->setForUser(101, 201, 402, -1), 'Dislike replaces like.');
        $assert($reactions->countsForComments([402], 101)[402] === ['likes' => 0, 'dislikes' => 1, 'userReaction' => -1], 'Only the latest sign remains visible.');
        $assert((int) $connection->query('SELECT COUNT(*) FROM comment_reactions')->fetchColumn() === 1, 'One actor has exactly one row per comment.');
        $assert($service->setForUser(101, 201, 402, 0) && $service->setForUser(101, 201, 402, 0), 'Zero clears and can be retried.');
        $assert($reactions->currentForUser(101, 402) === 0 && (int) $connection->query('SELECT COUNT(*) FROM comment_reactions')->fetchColumn() === 0, 'Neutral state is represented by no row.');
        $assert((int) $connection->query('SELECT COUNT(*) FROM community_activity')->fetchColumn() === 3, 'Only three actual changes were recorded.');
    });

    $run('counters combine actors while the selected reaction belongs only to the current viewer', static function () use ($service, $reactions, $assert): void {
        $service->setForUser(101, 201, 402, 1);
        $service->setForUser(103, 201, 402, -1);
        $service->setForUser(104, 201, 402, 1);
        $service->setForUser(102, 201, 401, 1);
        $assert($reactions->countsForComments([401, 402], 103) === [
            401 => ['likes' => 1, 'dislikes' => 0, 'userReaction' => 0],
            402 => ['likes' => 2, 'dislikes' => 1, 'userReaction' => -1],
        ], 'A dislike is preserved even when other users supplied positive votes.');
        $assert($reactions->countsForComments([402])[402] === ['likes' => 2, 'dislikes' => 1, 'userReaction' => 0], 'Anonymous projection contains totals and no account selection.');
        $assert($reactions->countsForComments([402], 101)[402]['userReaction'] === 1, 'Different viewer sees only their own selection.');
    });

    $run('active replies remain votable beneath deleted or moderated roots', static function () use ($service, $connection, $assert): void {
        $assert($service->setForUser(101, 201, 407, 1), 'Other user can react to a surviving reply under a deleted root.');
        $connection->exec('UPDATE anime_comments SET moderated_at = clock_timestamp() WHERE id = 401');
        $assert($service->setForUser(103, 201, 402, -1), 'Moderation of root does not prohibit reactions on another author visible reply.');
        $assert(!$service->setForUser(103, 201, 407, 1), 'Reply author still cannot react to own text.');
    });

    $run('new visibility checks prevent changing reactions on removed targets and hide their totals', static function () use ($service, $reactions, $connection, $assert): void {
        $service->setForUser(101, 201, 402, 1);
        foreach (['moderated_at', 'deleted_at'] as $column) {
            $connection->exec('UPDATE anime_comments SET ' . $column . ' = clock_timestamp() WHERE id = 402');
            $assert(!$service->setForUser(101, 201, 402, -1) && !$service->setForUser(101, 201, 402, 0), 'Hidden target rejects update and removal.');
            $assert($reactions->countsForComments([402], 101)[402] === ['likes' => 0, 'dislikes' => 0, 'userReaction' => 0], 'Old votes on hidden text never appear in public projection.');
            $connection->exec('UPDATE anime_comments SET ' . $column . ' = NULL WHERE id = 402');
        }
        $assert($reactions->currentForUser(101, 402) === 1, 'Rejected requests never mutate the prior stored state.');
    });

    $run('changing back immediately is allowed and uses only the reaction quota', static function () use ($service, $reactions, $connection, $assert): void {
        foreach ([1, -1, 0, 1] as $value) {
            $assert($service->setForUser(101, 201, 402, $value), 'Returning to a previous state is valid within 30 seconds.');
        }
        $assert($reactions->currentForUser(101, 402) === 1, 'Last desired state wins.');
        $assert((int) $connection->query("SELECT COUNT(*) FROM community_activity WHERE action = 'reaction'")->fetchColumn() === 4, 'Each actual state change is recorded under its own action.');
    });

    $run('reaction quota allows 60 actual changes then preserves state with Retry-After and permits no-op retries', static function () use ($service, $reactions, $connection, $exceptionOf, $assert): void {
        $create = $connection->prepare("INSERT INTO anime_comments (user_id, anime_id, body) VALUES (102, 201, :body) RETURNING id");
        $ids = [];
        for ($index = 0; $index < 61; $index++) {
            $create->execute(['body' => 'Quota target ' . $index]);
            $ids[] = (int) $create->fetchColumn();
        }
        for ($index = 0; $index < 60; $index++) {
            $assert($service->setForUser(101, 201, $ids[$index], 1), 'A change up to the exact quota is allowed.');
        }
        $exception = $exceptionOf(RateLimitException::class, static fn () => $service->setForUser(101, 201, $ids[60], 1));
        $assert($exception->retryAfter >= 1 && $exception->retryAfter <= 60, 'Rate limit reports a bounded retry delay.');
        $assert($reactions->currentForUser(101, $ids[60]) === 0, 'Over-quota mutation never reaches storage.');
        $assert($service->setForUser(101, 201, $ids[0], 1), 'Idempotent retry remains valid at exhausted quota.');
        $exceptionOf(RateLimitException::class, static fn () => $service->setForUser(101, 201, $ids[0], 0));
        $assert($reactions->currentForUser(101, $ids[0]) === 1, 'Over-quota removal also preserves existing state.');
        $assert((int) $connection->query("SELECT COUNT(*) FROM community_activity WHERE user_id = 101 AND action = 'reaction'")->fetchColumn() === 60, 'Rejected changes and retries do not spend quota.');
        $assert($service->setForUser(103, 201, $ids[60], -1), 'Another account has an independent quota.');
    });

    $run('expired reaction quota and comment activity do not block a new reaction', static function () use ($service, $connection, $assert): void {
        $insert = $connection->prepare("INSERT INTO community_activity (user_id, action, content_hash, created_at) VALUES (101, :action, :hash, clock_timestamp() - make_interval(secs => :age))");
        for ($index = 0; $index < 60; $index++) {
            $insert->execute(['action' => 'reaction', 'hash' => hash('sha256', 'Old ' . $index), 'age' => 61]);
        }
        for ($index = 0; $index < 15; $index++) {
            $insert->execute(['action' => 'comment', 'hash' => hash('sha256', 'Comment ' . $index), 'age' => 0]);
        }
        $assert($service->setForUser(101, 201, 402, 1), 'Expired and unrelated actions do not count against the active reaction window.');
    });

    $run('reaction and ledger writes roll back together when recording the successful change fails', static function () use ($service, $reactions, $connection, $exceptionOf, $assert): void {
        $connection->exec(<<<'SQL'
CREATE FUNCTION pg_temp.reject_reaction_ledger() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION 'Simulated ledger failure' USING ERRCODE = '23514';
END;
$$;
CREATE TRIGGER reject_reaction_ledger BEFORE INSERT ON pg_temp.community_activity
    FOR EACH ROW WHEN (NEW.action = 'reaction') EXECUTE FUNCTION pg_temp.reject_reaction_ledger();
SQL);
        $exception = $exceptionOf(PDOException::class, static fn () => $service->setForUser(101, 201, 402, 1));
        $assert($exception->getCode() === '23514' && $connection->inTransaction(), 'Nested failure preserves the caller transaction.');
        $assert($reactions->currentForUser(101, 402) === 0, 'Reaction is rolled back with the failed ledger insert.');
        $assert((int) $connection->query('SELECT COUNT(*) FROM community_activity')->fetchColumn() === 0, 'No partial quota consumption survives.');
    });

    $run('database constraints reject duplicate signs, zero rows and orphan references', static function () use ($reactions, $connection, $assert): void {
        $assert($reactions->setForUser(101, 201, 402, 1), 'Initial like stored through guarded repository path.');
        foreach ([[101, 402, -1, '23505'], [103, 402, 0, '23514'], [999, 402, 1, '23503'], [103, 999, 1, '23503']] as [$actor, $comment, $value, $code]) {
            $connection->exec('SAVEPOINT invalid_reaction');
            try {
                $rejected = false;
                try {
                    $insert = $connection->prepare('INSERT INTO comment_reactions (user_id, comment_id, value) VALUES (:actor, :comment, :value)');
                    $insert->execute(['actor' => $actor, 'comment' => $comment, 'value' => $value]);
                } catch (PDOException $exception) {
                    $rejected = $exception->getCode() === $code;
                }
                $assert($rejected, 'Database must reject invalid direct reaction rows.');
            } finally {
                $connection->exec('ROLLBACK TO SAVEPOINT invalid_reaction');
                $connection->exec('RELEASE SAVEPOINT invalid_reaction');
            }
        }
    });

    $run('deleting an actor or target removes only associated reaction rows', static function () use ($reactions, $connection, $assert): void {
        $reactions->setForUser(101, 201, 402, 1);
        $reactions->setForUser(104, 201, 402, -1);
        $reactions->setForUser(104, 201, 403, 1);
        $connection->exec('DELETE FROM users WHERE id = 101');
        $assert($reactions->countsForComments([403])[403]['likes'] === 1, 'Deleting root author and its thread does not remove unrelated reactions.');
        $assert((int) $connection->query('SELECT COUNT(*) FROM comment_reactions WHERE comment_id = 402')->fetchColumn() === 0, 'Deleted thread reactions cascade with the target.');
        $connection->exec('DELETE FROM anime_comments WHERE id = 403');
        $assert((int) $connection->query('SELECT COUNT(*) FROM comment_reactions')->fetchColumn() === 0, 'Removing final target cleans its reactions.');
    });
} catch (Throwable $exception) {
    $failed++;
    fwrite(STDERR, 'FAIL reaction fixture: ' . $exception->getMessage() . PHP_EOL);
} finally {
    if ($connection instanceof PDO && $connection->inTransaction()) {
        $connection->rollBack();
    }
}

echo $passed . ' passed, ' . $failed . ' failed.' . PHP_EOL;
exit($failed === 0 ? 0 : 1);
