BEGIN;

ALTER TABLE users ADD COLUMN IF NOT EXISTS is_admin BOOLEAN NOT NULL DEFAULT false;

CREATE TABLE IF NOT EXISTS admin_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    actor_name VARCHAR(120) NOT NULL,
    target_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    target_name VARCHAR(120) NULL,
    action VARCHAR(50) NOT NULL CHECK (action ~ '^[a-z][a-z0-9_]{0,49}$'),
    details JSONB NOT NULL DEFAULT '{}' CHECK (jsonb_typeof(details) = 'object' AND char_length(details::text) <= 8192),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS admin_actions_created_idx ON admin_actions (created_at DESC, id DESC);
CREATE INDEX IF NOT EXISTS admin_actions_actor_created_idx ON admin_actions (actor_id, created_at DESC, id DESC);

COMMIT;
