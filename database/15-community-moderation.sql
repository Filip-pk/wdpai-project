BEGIN;

ALTER TABLE users ADD COLUMN is_moderator BOOLEAN NOT NULL DEFAULT false;
ALTER TABLE anime_comments ADD COLUMN moderated_at TIMESTAMPTZ NULL;
ALTER TABLE private_messages ADD COLUMN moderated_at TIMESTAMPTZ NULL;

CREATE TABLE private_message_reads (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    conversation_id BIGINT NOT NULL REFERENCES private_conversations (id) ON DELETE CASCADE,
    last_read_message_id BIGINT NOT NULL DEFAULT 0 CHECK (last_read_message_id >= 0),
    PRIMARY KEY (user_id, conversation_id)
);

CREATE TABLE user_blocks (
    blocker_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    blocked_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (blocker_id, blocked_id),
    CHECK (blocker_id <> blocked_id)
);
CREATE INDEX user_blocks_blocked_id_idx ON user_blocks (blocked_id);

CREATE TABLE community_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    action VARCHAR(20) NOT NULL CHECK (action IN ('message', 'comment', 'report')),
    content_hash CHAR(64) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);
CREATE INDEX community_activity_user_action_created_idx
    ON community_activity (user_id, action, created_at DESC);

CREATE TABLE community_reports (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reporter_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    reported_user_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    target_type VARCHAR(20) NOT NULL CHECK (target_type IN ('comment', 'message')),
    target_id BIGINT NOT NULL CHECK (target_id > 0),
    snapshot TEXT NOT NULL,
    reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 1000 AND btrim(reason) <> ''),
    status VARCHAR(20) NOT NULL DEFAULT 'open' CHECK (status IN ('open', 'dismissed', 'removed')),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    resolved_by BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    resolved_at TIMESTAMPTZ NULL,
    UNIQUE (reporter_id, target_type, target_id)
);
CREATE INDEX community_reports_status_created_idx ON community_reports (status, created_at DESC, id DESC);

COMMIT;
