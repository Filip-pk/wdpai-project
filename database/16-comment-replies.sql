BEGIN;

ALTER TABLE public.anime_comments ADD COLUMN parent_id BIGINT NULL;
ALTER TABLE public.anime_comments ADD COLUMN deleted_at TIMESTAMPTZ NULL;
ALTER TABLE public.anime_comments ADD CONSTRAINT anime_comments_id_anime_unique UNIQUE (id, anime_id);
ALTER TABLE public.anime_comments ADD CONSTRAINT anime_comments_parent_fk
    FOREIGN KEY (parent_id, anime_id) REFERENCES public.anime_comments (id, anime_id) ON DELETE CASCADE;
ALTER TABLE public.anime_comments ADD CONSTRAINT anime_comments_not_own_parent CHECK (parent_id IS NULL OR parent_id <> id);

CREATE INDEX anime_comments_roots_created_idx
    ON public.anime_comments (anime_id, created_at DESC, id DESC) WHERE parent_id IS NULL;
CREATE INDEX anime_comments_parent_created_idx
    ON public.anime_comments (parent_id, created_at ASC, id ASC) WHERE parent_id IS NOT NULL;

CREATE FUNCTION public.enforce_anime_comment_parent() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    parent_comment RECORD;
BEGIN
    IF TG_OP = 'UPDATE' AND (NEW.parent_id IS DISTINCT FROM OLD.parent_id OR NEW.anime_id IS DISTINCT FROM OLD.anime_id) THEN
        RAISE EXCEPTION 'Comment thread cannot be changed' USING ERRCODE = '23514';
    END IF;
    IF NEW.parent_id IS NULL THEN
        RETURN NEW;
    END IF;

    -- The trigger also works with isolated temporary tables used by repository tests.
    EXECUTE format('SELECT id, parent_id, deleted_at, moderated_at FROM %I.%I WHERE id = $1 AND anime_id = $2 FOR UPDATE', TG_TABLE_SCHEMA, TG_TABLE_NAME)
        INTO parent_comment USING NEW.parent_id, NEW.anime_id;
    IF parent_comment.id IS NULL THEN
        RAISE EXCEPTION 'Comment parent does not exist in this anime' USING ERRCODE = '23503';
    END IF;
    IF parent_comment.parent_id IS NOT NULL OR parent_comment.deleted_at IS NOT NULL OR parent_comment.moderated_at IS NOT NULL THEN
        RAISE EXCEPTION 'Replies require an active top-level comment' USING ERRCODE = '23514';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER anime_comments_parent_guard
    BEFORE INSERT OR UPDATE OF parent_id, anime_id ON public.anime_comments
    FOR EACH ROW EXECUTE FUNCTION public.enforce_anime_comment_parent();

CREATE TABLE public.comment_reply_notifications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    reply_id BIGINT NOT NULL UNIQUE REFERENCES public.anime_comments (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    read_at TIMESTAMPTZ NULL
);
CREATE INDEX comment_reply_notifications_user_created_idx
    ON public.comment_reply_notifications (user_id, created_at DESC, id DESC);
CREATE INDEX comment_reply_notifications_unread_idx
    ON public.comment_reply_notifications (user_id, id DESC) WHERE read_at IS NULL;

COMMIT;
