CREATE TABLE public.anime (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mal_id INTEGER UNIQUE CHECK (mal_id > 0),
    title VARCHAR(255) NOT NULL,
    alternative_titles JSONB NOT NULL DEFAULT '[]' CHECK (jsonb_typeof(alternative_titles) = 'array'),
    description TEXT NOT NULL DEFAULT '',
    description_language VARCHAR(10) NOT NULL DEFAULT 'en',
    cover_url TEXT NULL,
    episodes INTEGER NULL CHECK (episodes >= 0),
    score NUMERIC(4, 2) NULL CHECK (score BETWEEN 0 AND 10),
    studio TEXT NOT NULL DEFAULT '',
    release_year SMALLINT NULL CHECK (release_year BETWEEN 1900 AND 2200),
    media_type VARCHAR(20) NOT NULL DEFAULT 'UNKNOWN',
    source_url TEXT NULL,
    source_updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX anime_title_idx ON public.anime (LOWER(title), id);

CREATE TABLE public.genres (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id INTEGER NOT NULL UNIQUE CHECK (source_id > 0),
    name VARCHAR(100) NOT NULL
);

CREATE TABLE public.anime_genres (
    anime_id BIGINT NOT NULL REFERENCES public.anime (id) ON DELETE CASCADE,
    genre_id INTEGER NOT NULL REFERENCES public.genres (id) ON DELETE CASCADE,
    PRIMARY KEY (anime_id, genre_id)
);

CREATE INDEX anime_genres_genre_idx ON public.anime_genres (genre_id, anime_id);

