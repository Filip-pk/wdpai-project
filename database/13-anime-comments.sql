BEGIN;

CREATE TABLE public.anime_comments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anime_id BIGINT NOT NULL REFERENCES public.anime (id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 2000 AND btrim(body) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NULL
);

CREATE INDEX anime_comments_anime_created_idx ON public.anime_comments (anime_id, created_at DESC, id DESC);
CREATE INDEX anime_comments_user_idx ON public.anime_comments (user_id);

COMMIT;
