BEGIN;

-- Failed sign-ins for the attempt limit. The e-mail address and IP address
-- are stored only as SHA-256 hashes; passwords are never stored.
CREATE TABLE IF NOT EXISTS login_attempts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email_hash CHAR(64) NOT NULL CHECK (email_hash ~ '^[a-f0-9]{64}$'),
    ip_hash CHAR(64) NOT NULL CHECK (ip_hash ~ '^[a-f0-9]{64}$'),
    attempted_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE INDEX IF NOT EXISTS login_attempts_account_idx ON login_attempts (ip_hash, email_hash, attempted_at);
CREATE INDEX IF NOT EXISTS login_attempts_attempted_idx ON login_attempts (attempted_at);

COMMIT;
