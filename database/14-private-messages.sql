BEGIN;

CREATE TABLE public.private_conversations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    second_user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (first_user_id < second_user_id),
    UNIQUE (first_user_id, second_user_id)
);

CREATE INDEX private_conversations_second_user_idx ON public.private_conversations (second_user_id);

CREATE TABLE public.private_messages (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    conversation_id BIGINT NOT NULL REFERENCES public.private_conversations (id) ON DELETE CASCADE,
    sender_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    body TEXT NOT NULL CHECK (char_length(body) BETWEEN 1 AND 4000 AND btrim(body) <> ''),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX private_messages_conversation_id_idx ON public.private_messages (conversation_id, id DESC);
CREATE INDEX private_messages_sender_idx ON public.private_messages (sender_id);

COMMIT;
