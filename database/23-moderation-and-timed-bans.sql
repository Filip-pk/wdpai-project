BEGIN;

CREATE TABLE user_bans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    moderator_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 1000 AND btrim(reason) <> ''),
    starts_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    ends_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ NULL,
    revoked_by BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    revoke_reason TEXT NULL,
    CHECK (ends_at > starts_at),
    CHECK (user_id IS DISTINCT FROM moderator_id),
    CHECK ((revoked_at IS NULL AND revoked_by IS NULL AND revoke_reason IS NULL)
        OR (revoked_at IS NOT NULL AND char_length(revoke_reason) BETWEEN 1 AND 1000 AND btrim(revoke_reason) <> ''))
);
CREATE INDEX user_bans_active_user_idx ON user_bans (user_id, ends_at DESC) WHERE revoked_at IS NULL;

CREATE TABLE moderation_actions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    moderator_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    moderator_name VARCHAR(120) NOT NULL,
    user_id BIGINT NULL REFERENCES users (id) ON DELETE SET NULL,
    user_name VARCHAR(120) NOT NULL,
    action_type VARCHAR(30) NOT NULL CHECK (action_type IN ('comment_removed', 'warning', 'ban', 'ban_revoked', 'report_dismissed')),
    comment_id BIGINT NULL REFERENCES anime_comments (id) ON DELETE SET NULL,
    report_id BIGINT NULL REFERENCES community_reports (id) ON DELETE SET NULL,
    ban_id BIGINT NULL REFERENCES user_bans (id) ON DELETE SET NULL,
    anime_title TEXT NULL,
    reason TEXT NOT NULL CHECK (char_length(reason) BETWEEN 1 AND 1000 AND btrim(reason) <> ''),
    ends_at TIMESTAMPTZ NULL,
    request_key VARCHAR(64) NOT NULL CHECK (request_key ~ '^[a-f0-9]{32,64}$'),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (moderator_id, request_key)
);
CREATE INDEX moderation_actions_created_idx ON moderation_actions (created_at DESC, id DESC);
CREATE INDEX moderation_actions_user_created_idx ON moderation_actions (user_id, created_at DESC, id DESC);

CREATE TABLE moderation_notices (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    action_id BIGINT NOT NULL UNIQUE REFERENCES moderation_actions (id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    read_at TIMESTAMPTZ NULL
);
CREATE INDEX moderation_notices_user_created_idx ON moderation_notices (user_id, created_at DESC, id DESC);
CREATE INDEX moderation_notices_unread_idx ON moderation_notices (user_id, id DESC) WHERE read_at IS NULL;

COMMIT;
