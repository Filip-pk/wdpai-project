BEGIN;

-- A snapshot keeps a published daily quiz stable when the source question pool changes.
CREATE TABLE daily_quizzes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_date DATE NOT NULL UNIQUE,
    questions JSONB NOT NULL CHECK (jsonb_typeof(questions) = 'array' AND jsonb_array_length(questions) = 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE quiz_attempts (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    quiz_id BIGINT NOT NULL REFERENCES daily_quizzes (id),
    score SMALLINT NOT NULL CHECK (score BETWEEN 0 AND 5),
    answers JSONB NOT NULL CHECK (jsonb_typeof(answers) = 'object'),
    completed_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (user_id, quiz_id)
);

CREATE INDEX quiz_attempts_quiz_idx ON quiz_attempts (quiz_id);

COMMIT;
