BEGIN;

CREATE TABLE daily_anime_clues (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    game_date DATE NOT NULL UNIQUE,
    entries JSONB NOT NULL CHECK (jsonb_typeof(entries) = 'array' AND jsonb_array_length(entries) = 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp()
);

CREATE TABLE anime_clue_attempts (
    user_id BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    game_id BIGINT NOT NULL REFERENCES daily_anime_clues (id),
    round_index SMALLINT NOT NULL DEFAULT 0 CHECK (round_index BETWEEN 0 AND 5),
    hints_used SMALLINT NOT NULL DEFAULT 1 CHECK (hints_used BETWEEN 1 AND 3),
    score SMALLINT NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 15),
    correct_count SMALLINT NOT NULL DEFAULT 0 CHECK (correct_count BETWEEN 0 AND 5),
    completed_at TIMESTAMPTZ,
    PRIMARY KEY (user_id, game_id),
    CHECK ((round_index = 5) = (completed_at IS NOT NULL)),
    CHECK (correct_count <= round_index AND score <= correct_count * 3)
);

CREATE TABLE anime_clue_answers (
    user_id BIGINT NOT NULL,
    game_id BIGINT NOT NULL,
    round_index SMALLINT NOT NULL CHECK (round_index BETWEEN 0 AND 4),
    answer TEXT NOT NULL CHECK (char_length(answer) <= 200),
    correct BOOLEAN NOT NULL,
    points SMALLINT NOT NULL CHECK (points BETWEEN 0 AND 3),
    hints_used SMALLINT NOT NULL CHECK (hints_used BETWEEN 1 AND 3),
    skipped BOOLEAN NOT NULL DEFAULT FALSE,
    answered_at TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    PRIMARY KEY (user_id, game_id, round_index),
    FOREIGN KEY (user_id, game_id) REFERENCES anime_clue_attempts (user_id, game_id) ON DELETE CASCADE,
    CHECK ((correct AND NOT skipped AND points = 4 - hints_used) OR (NOT correct AND points = 0)),
    CHECK (NOT skipped OR answer = '')
);

CREATE INDEX anime_clue_attempts_game_idx ON anime_clue_attempts (game_id);

COMMIT;
