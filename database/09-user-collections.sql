BEGIN;

CREATE TABLE public.anime_collections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES public.users (id) ON DELETE CASCADE,
    name VARCHAR(120) NOT NULL CHECK (char_length(BTRIM(name)) BETWEEN 1 AND 120),
    description VARCHAR(500) NOT NULL DEFAULT '',
    is_default BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX anime_collections_user_idx ON public.anime_collections (user_id, id);
CREATE UNIQUE INDEX anime_collections_default_user_idx
    ON public.anime_collections (user_id) WHERE is_default;

CREATE TABLE public.anime_collection_items (
    collection_id BIGINT NOT NULL REFERENCES public.anime_collections (id) ON DELETE CASCADE,
    anime_id BIGINT NOT NULL REFERENCES public.anime (id) ON DELETE CASCADE,
    added_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (collection_id, anime_id)
);

CREATE INDEX anime_collection_items_preview_idx
    ON public.anime_collection_items (collection_id, added_at DESC, anime_id DESC);
CREATE INDEX anime_collection_items_anime_idx
    ON public.anime_collection_items (anime_id, collection_id);

INSERT INTO public.anime_collections (user_id, name, is_default)
SELECT id, 'moja kolekcja', TRUE FROM public.users;

COMMIT;
